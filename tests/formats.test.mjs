// tests/formats.test.mjs — a harness change never breaks a game: the studio reads every edit format
// the engine ever had, writes each game only a format its own engine copy reads (or nothing, saying
// why), `yak check` names a file the game would quietly ignore, and the generated index modules a game
// imports are frozen byte for byte.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import fss from 'node:fs';
import path from 'node:path';
import * as D from '../studio/data/index.mjs';
import { copyEngine } from '../studio/data/engine-copy.mjs';
import * as ART from '../engine/art/edits.js';
import * as SND from '../engine/sound/edits.js';

const ID = `zz-formats-${process.pid}`;
const SHARED = `zz-formats-shared-${process.pid}`;
const dir = path.join(D.DIRS.games, ID);
const rm = (p) => fs.rm(p, { recursive: true, force: true, maxRetries: 20, retryDelay: 150 });
const edit = (format) => ({ format, asset: 'hero', poses: { idle: { mode: 'baked', rows: ['a.'] } }, legend: { a: '#ff00aa' } });
const copyArt = path.join(dir, 'engine', 'art', 'edits.js');

test.before(async () => {
  for (const id of [ID, SHARED]) {
    await fs.mkdir(path.join(D.DIRS.games, id), { recursive: true });
    await fs.writeFile(path.join(D.DIRS.games, id, 'game.json'), JSON.stringify({ id, name: 'Formats test' }));
  }
  copyEngine(ID); // its own copy of the harness's engine, as every new game gets
});
test.after(async () => { await rm(dir); await rm(path.join(D.DIRS.games, SHARED)); });

test('every format an engine writes is one it reads', () => {
  assert.ok(ART.EDITS_FORMATS.includes(ART.EDITS_FORMAT));
  assert.ok(SND.SOUND_EDIT_FORMATS.includes(SND.SOUND_EDIT_FORMAT));
});

test("the studio reads a game's formats from its engine copy as text, the same list the engine has", async () => {
  assert.deepEqual(await D.gameReads(ID, 'edits'), [...ART.EDITS_FORMATS]);
  assert.deepEqual(await D.gameReads(ID, 'sound'), [...SND.SOUND_EDIT_FORMATS]);
  assert.equal(await D.gameReads(SHARED, 'edits'), null); // no copy of its own: it reads what the harness reads
  assert.equal(await D.formatFor(SHARED, 'edits', ART.EDITS_FORMAT), ART.EDITS_FORMAT);
});

test('an edit in an older format stays readable when a newer one is added', () => {
  const later = [ART.EDITS_FORMAT, 'pixel-studio-edits@99'];
  assert.deepEqual(ART.checkEdit(edit(ART.EDITS_FORMAT), later), []);
  assert.deepEqual(ART.checkEdit(edit('pixel-studio-edits@99'), later), []);
  assert.match(ART.checkEdit(edit('pixel-studio-edits@99'))[0], /isn't one this engine reads/);
  const snd = (format) => ({ format, kind: 'instruments', game: 'x', instruments: {} });
  assert.deepEqual(SND.checkSoundEdit(snd(SND.SOUND_EDIT_FORMAT), [SND.SOUND_EDIT_FORMAT, 'pixel-yak-sound-edit@99']), []);
  assert.match(SND.checkSoundEdit(snd('pixel-yak-sound-edit@99'))[0], /isn't one this engine reads/);
});

test("a game on an older engine is never written a format it can't read — nothing is saved, and the error says what to do", async () => {
  const theirs = await fs.readFile(copyArt, 'utf8');
  try {
    // an engine copy from before the list existed: one format, and not the harness's
    await fs.writeFile(copyArt, "export const EDITS_FORMAT = 'pixel-studio-edits@0';\n");
    assert.deepEqual(await D.gameReads(ID, 'edits'), ['pixel-studio-edits@0']);
    await assert.rejects(D.writeEdit(ID, 'hero', edit(ART.EDITS_FORMAT)), /Not saved: .*pixel-studio-edits@0.*engine-pull/s);
    assert.equal(fss.existsSync(path.join(dir, 'game', 'art', 'edits', 'hero.json')), false);
    await assert.rejects(D.formatFor(ID, 'sound', 'pixel-yak-sound-edit@99'), /Not saved/);
  } finally { await fs.writeFile(copyArt, theirs); }
  const saved = await D.writeEdit(ID, 'hero', edit('whatever-the-ui-sent'));
  assert.equal(saved.format, ART.EDITS_FORMAT); // stamped with the format the game reads
});

test("yak check names an edit file the game's own engine would quietly ignore", async () => {
  const theirs = await fs.readFile(copyArt, 'utf8');
  try {
    await fs.mkdir(path.join(dir, 'game', 'art', 'edits'), { recursive: true });
    await fs.writeFile(path.join(dir, 'game', 'art', 'edits', 'hero.json'), JSON.stringify(edit(ART.EDITS_FORMAT)));
    await fs.writeFile(copyArt, "export const EDITS_FORMAT = 'pixel-studio-edits@0';\n");
    const lines = await D.checkProject(ID);
    assert.ok(lines.some((l) => /^ERROR .*hero\.json is pixel-studio-edits@1, which this game's own engine doesn't read/.test(l)), lines.join('\n'));
  } finally { await fs.writeFile(copyArt, theirs); }
});

test('the generated index modules a game imports never change shape', () => {
  assert.equal(ART.editsIndexSource({ b: { x: 1 }, a: { y: 2 } }),
    '// GENERATED by Pixel Yak from the *.json files in this folder. Do not edit by hand:\n'
    + '// edit the JSON (or paint in the studio) and run `node cli/yak.mjs edits-index <project>`.\n'
    + 'export const EDITS = {\n  "a": {"y":2},\n  "b": {"x":1}\n};\n');
  assert.equal(ART.editsIndexSource({}).split('\n')[2], 'export const EDITS = {};');
  assert.deepEqual(ART.parseEditsIndexSource(ART.editsIndexSource({ a: { y: 2 } })), { a: { y: 2 } });
  assert.equal(SND.editsIndexSource({ songs: { s: { k: 1 } } }),
    "// Generated by Pixel Yak from the sound edit files next to this one — don't edit by hand\n"
    + '// (the user\'s own changes to the music and sound effects; docs/contracts/SOUND.md).\n'
    + 'export const SOUND_EDITS = {"songs":{"s":{"k":1}},"sfx":{},"instruments":{}};\n');
  assert.deepEqual(SND.parseEditsIndexSource(SND.editsIndexSource({ songs: { s: { k: 1 } } })), { songs: { s: { k: 1 } }, sfx: {}, instruments: {} });
});
