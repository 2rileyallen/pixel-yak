// cli/commands/learn.mjs — what the AI learns from the user's edits: each game's lessons
// (games/<id>/design/lessons/) and the distillations a smart model made of them (skill art-learn).
import { D, out, fail, ago, gameArg } from '../lib.mjs';

export const section = { title: 'Learning (the user\'s edits → the game\'s design files)', order: 30 };

export const commands = {
  lessons: {
    usage: 'lessons [game] [--new] [--limit N] [--rows]',
    help: 'without a game: every game\'s lesson counts. With one: its lessons, newest\nlast (--new: only those not distilled yet; --rows: the pixel rows too)',
    async run({ pos, opt }) {
      if (!pos[0]) {
        const all = await D.listStyles();
        if (!all.length) { out('No game has a design/ folder yet.'); return; }
        for (const s of all) out(`- ${s.id} — ${s.name} v${s.version} · ${s.lessons} lessons · ${s.undistilled} not distilled yet${s.from ? ` · started from designs/art/${s.from}` : ''}`);
        return;
      }
      const p = await gameArg(pos[0]);
      if (!p.style) fail(`${p.id} has no design/ folder yet (skill design)`);
      const sum = await D.styleSummary(p.id);
      let ls = (await D.readLessons(p.id, { limit: 100000, full: !!opt.rows })).reverse(); // oldest first
      if (opt.new && sum.lastDistilled && sum.lastDistilled.through) {
        const i = ls.findIndex((l) => l.id === sum.lastDistilled.through);
        if (i >= 0) ls = ls.slice(i + 1);
      }
      const limit = Number(opt.limit) || 40;
      ls = ls.slice(-limit);
      out(`# Lessons for ${p.id} (look v${sum.version}) — ${ls.length} shown, ${sum.undistilled} not distilled yet · rules: games/${p.id}/design/art.md`);
      out(`Each card image shows: AI generated | before this save | after | changes (magenta). Look at the cards.\n`);
      for (const l of ls) {
        const m = l.save || {};
        out(`## ${l.id}`);
        out(`${l.asset}:${l.pose} · ${l.kind}${l.from ? ` (new frame copied from ${l.from})` : ''} · ${ago(l.ts)}${l.gen ? ` · generated by ${l.gen.by || '?'} with ${l.gen.style || '?'} v${l.gen.v || '?'}` : ' · generator not stamped'}`);
        if (l.note) out(`user's note: "${l.note}"`);
        out(`this save: ${m.changed} px — +${m.added} silhouette, −${m.removed} silhouette, ${m.lighter} lighter, ${m.darker} darker, ${(m.recolored || 0) - (m.lighter || 0) - (m.darker || 0)} recolored${m.outline ? `, INK outline ${m.outline.before}→${m.outline.after}` : ''}${m.bbox ? `, region ${m.bbox.join(',')}` : ''}`);
        if (l.total) out(`vs. the AI's frame: ${l.total.changed} px = ${l.total.repaintPct}% repainted`);
        if (m.materials && Object.keys(m.materials).length) out(`by material: ${Object.entries(m.materials).map(([k, o]) => `${k}(${Object.entries(o).filter(([, v]) => v).map(([a, v]) => `${a} ${v}`).join(', ')})`).join('; ')}`);
        if (m.transitions && m.transitions.length) out(`top swaps: ${m.transitions.slice(0, 8).map(([k, n]) => `${k}×${n}`).join('  ')}`);
        out(`card: games/${p.id}/design/lessons/${l.card}`);
        if (opt.rows && l.rows) {
          out(`legend: ${Object.entries(l.legend || {}).map(([k, v]) => `${k}=${Array.isArray(v) ? v.join(' ') : v}`).join(' ')}`);
          for (const [k, rows] of Object.entries(l.rows)) { out(`${k}:`); rows.forEach((r) => out('  ' + r)); }
        }
        out('');
      }
      if (ls.length) out(`When done: node cli/yak.mjs distilled ${p.id} --version ${sum.version + 1} --through ${ls[ls.length - 1].id} --summary "<what you learned>"`);
    },
  },

  distilled: {
    usage: 'distilled <game> --version N --through <lessonId> --summary "…"',
    help: 'record a distillation (after updating design/art.md and the generators)',
    async run({ pos, opt }) {
      const p = await gameArg(pos[0]);
      if (!opt.version || !opt.through || !opt.summary) fail('usage: distilled <game> --version N --through <lessonId> --summary "…"');
      const e = await D.addDistilled(p.id, { version: Number(opt.version), through: String(opt.through), summary: String(opt.summary) });
      out(`recorded distillation v${e.version} through ${e.through}`);
    },
  },
};
